/**
 * One-time conversion: Supabase backup JSON -> D1 SQLite data (d1/data.sql).
 *
 * Reads the backup produced by scripts/backup-supabase.mjs from
 * docs/archive/supabase/ (latest manifest), transforms rows to the D1
 * schema (d1/migrations/0001_schema.sql), and emits SQLite INSERT
 * statements including the derived market_days rows.
 * Public export only: never reads or exports private market suggestions.
 *
 * Usage:
 *   node scripts/export-supabase-d1.mjs
 */

import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { writeFile } from "node:fs/promises";

const BACKUP_DIR = path.join("docs", "archive", "supabase");
const OUT_FILE = path.join("d1", "data.sql");

const DAY_CODES = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"];

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? "1" : "0";
}

function sqlNumber(value) {
  if (value === null || value === undefined) return "NULL";
  return String(value);
}

function deriveScheduleDays(schedule) {
  const days = new Set();
  for (const entry of schedule ?? []) {
    for (const day of entry?.days ?? []) {
      if (!DAY_CODES.includes(day)) {
        throw new Error(`Unknown day code: ${day}`);
      }
      days.add(day);
    }
  }
  return [...days];
}

function marketDaysValues(marketId, schedule) {
  return deriveScheduleDays(schedule).map((day) => `'${marketId.replace(/'/g, "''")}', '${day}'`);
}

const manifest = JSON.parse(
  readFileSync(
    readdirSync(BACKUP_DIR)
      .filter((f) => f.startsWith("backup-manifest-"))
      .sort()
      .map((f) => path.join(BACKUP_DIR, f))
      .at(-1),
    "utf8",
  ),
);

const marketsFile = path.join(BACKUP_DIR, manifest.tables.pasar_malams.file);

const markets = JSON.parse(readFileSync(marketsFile, "utf8"));

console.log(`Read ${markets.length} public markets from backup`);

const marketValues = [];
const dayValues = [];

for (const m of markets) {
  const scheduleJson = JSON.stringify(Array.isArray(m.schedule) ? m.schedule : []);
  const locationJson = m.location === null || m.location === undefined ? null : JSON.stringify(m.location);

  marketValues.push(
    [
      sqlString(m.id),
      sqlString(m.name),
      sqlString(m.address),
      sqlString(m.district),
      sqlString(m.state),
      sqlString(m.status),
      sqlString(m.description),
      sqlNumber(m.area_m2),
      sqlNumber(m.total_shop),
      sqlBool(m.parking_available),
      sqlBool(m.parking_accessible),
      sqlString(m.parking_notes),
      sqlBool(m.amen_toilet),
      sqlBool(m.amen_prayer_room),
      locationJson === null ? "NULL" : sqlString(locationJson),
      sqlString(scheduleJson),
      sqlString(m.created_at),
      sqlString(m.updated_at),
      sqlString(m.shop_list),
    ].join(", "),
  );

  dayValues.push(...marketDaysValues(m.id, m.schedule));
}

function batchInserts(tableName, columns, values, batchSize = 20) {
  const stmts = [];
  for (let i = 0; i < values.length; i += batchSize) {
    const chunk = values.slice(i, i + batchSize);
    stmts.push(`INSERT INTO ${tableName} (${columns.join(", ")}) VALUES\n${chunk.map((v) => `(${v})`).join(",\n")};`);
  }
  return stmts;
}

const MARKET_COLUMNS = [
  "id",
  "name",
  "address",
  "district",
  "state",
  "status",
  "description",
  "area_m2",
  "total_shop",
  "parking_available",
  "parking_accessible",
  "parking_notes",
  "amen_toilet",
  "amen_prayer_room",
  "location",
  "schedule",
  "created_at",
  "updated_at",
  "shop_list",
];

const header = `-- Generated by scripts/export-supabase-d1.mjs on ${new Date().toISOString()}
-- Source: ${manifest.tables.pasar_malams.file}
-- Markets: ${markets.length}, market_days rows: ${dayValues.length}, suggestions: excluded (private data)
-- NOTE: no BEGIN/COMMIT — remote D1 (Durable Object storage) rejects explicit transactions.
`;

const footer = "";

const sql = [
  header,
  "-- pasar_malams",
  ...batchInserts("pasar_malams", MARKET_COLUMNS, marketValues),
  "",
  "-- market_days (derived from schedule JSON)",
  ...batchInserts("market_days", ["market_id", "day"], dayValues),
  "",
  footer,
].join("\n");

// Fail before overwriting the public export if free-text market fields contain email addresses.
if (/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i.test(sql)) {
  throw new Error("Public export contains an email address. Review the source market data before exporting.");
}

await writeFile(OUT_FILE, sql, "utf8");
console.log(`Wrote ${OUT_FILE} (${(sql.length / 1024).toFixed(1)} KB)`);
console.log(`Market days rows: ${dayValues.length}`);
